#!/usr/bin/env node
// Generate the bundled MCP Skills (SEP-2640) guides from the English VitePress
// guides. This makes docs/en/guide/*.md the single source of truth: the agent-
// facing SKILL.md files are derived, always English, and kept in lockstep by
// `skills:check` (wired into `pnpm check`). Edit the English guide, then run
// `skills:generate` — never edit a SKILL.md by hand.

import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirUrl = new URL('.', import.meta.url);
const projectRoot = fileURLToPath(new URL('../../', scriptDirUrl));
const enGuideDir = join(projectRoot, 'docs', 'en', 'guide');
const DOCS_BASE = 'https://vmoranv.github.io/jshookmcp';

/**
 * Frontmatter metadata is the only hand-maintained input. `name` must match the
 * folder and the lowercase-hyphen rule in the SDK (SkillFrontmatterSchema /
 * skillEntry validation); `description` is the string clients use to select a
 * skill via skills/list, so it stays English and descriptive.
 */
const GUIDES = [
  {
    name: 'best-practices',
    description:
      'Best practices for configuring and running jshookmcp: avoiding common pitfalls, plus performance and security guidance',
  },
  {
    name: 'configuration',
    description:
      'Configuration reference: every environment variable, profile, and threshold for jshookmcp',
  },
  {
    name: 'getting-started',
    description:
      'Get started with jshookmcp in five minutes: install, MCP client configuration, and the first tool call',
  },
  {
    name: 'telemetry',
    description:
      'Telemetry and observability: default-on metrics, OTLP export, search.query spans, and how to opt out',
  },
  {
    name: 'tool-selection',
    description:
      'Tool routing and lifecycle: 36-domain namespaces, on-demand activation, and how to select and schedule jshookmcp tools across profiles',
  },
  {
    name: 'troubleshooting',
    description:
      'Troubleshooting: diagnosis and fixes for install, connection, and tool-call failures in jshookmcp',
  },
];

const AUTO_NOTICE = [
  '# AUTO-GENERATED by scripts/generate/skills.mjs — DO NOT EDIT DIRECTLY.',
  '# Source of truth: docs/en/guide/<name>.md. Regenerate: corepack pnpm skills:generate',
].join('\n');

/**
 * Telemetry is a default-on, privacy-relevant behaviour whose disclosure must
 * reach the operator, not only an MCP client that opts into skills/list. The
 * canonical disclosure lives in README.md and DISCLOSURE (both shipped in the
 * npm package). The skill keeps a short prologue pointing there so an agent
 * that does load this skill still sees the important fact.
 */
const TELEMETRY_PROLOGUE = [
  '> **Operator notice:** telemetry is ON by default (opt-out) and exports',
  '> minimal tool/search usage to the maintainer OTLP endpoint. The full',
  '> data-minimisation table and the `JSHOOK_OBSERVABILITY_EXPORTER=none`',
  '> opt-out are documented for operators in the project README (`## Telemetry`)',
  '> and the published DISCLOSURE file. This skill is a convenience pointer, not',
  '> the primary disclosure channel.',
  '',
  '',
].join('\n');

/**
 * Convert VitePress-flavoured markdown into portable skill markdown:
 *  - `::: warning Note` / `::: danger Anti-Pattern` admonition openers become a
 *    bold lead-in (matching the original conversion in commit 3ae36ec8);
 *  - the standalone `:::` closer is dropped;
 *  - site-absolute doc links (/en/..., /guide/...) become full https URLs so
 *    the skill is self-contained when read outside the VitePress site.
 */
function toSkillBody(source) {
  const lines = source.replace(/\r\n/g, '\n').split('\n');
  const out = [];
  for (const line of lines) {
    const admonition = /^:::\s+(warning|danger|tip|info|note)\s+(.+?)\s*$/i.exec(line);
    if (admonition) {
      out.push(`**${admonition[2]}**`);
      continue;
    }
    if (/^:::\s*$/.test(line)) continue; // standalone closer
    out.push(
      line
        .replace(/\]\(\/en\//g, `](${DOCS_BASE}/en/`)
        .replace(/\]\(\/(guide|operations|reference|extensions)\//g, `](${DOCS_BASE}/$1/`),
    );
  }
  return out.join('\n').replace(/\n+$/, '\n');
}

// The SDK frontmatter parser is a minimal YAML reader: plain scalar values
// cannot contain ": " (assertPlain) and a few leading characters. Quote the
// description so its human-readable colons/commas survive verbatim.
function yamlQuote(value) {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

async function buildSkill(guide) {
  const source = await readFile(join(enGuideDir, `${guide.name}.md`), 'utf8');
  // SEP-2640 requires SKILL.md to begin with the `---` frontmatter fence, so the
  // generation notice lives inside frontmatter (a YAML comment), not before it.
  const header = `---\n${AUTO_NOTICE}\nname: ${guide.name}\ndescription: ${yamlQuote(guide.description)}\n---\n\n`;
  const prologue = guide.name === 'telemetry' ? TELEMETRY_PROLOGUE : '';
  return `${header}${prologue}${toSkillBody(source)}`;
}

async function computeState() {
  const files = [];
  for (const guide of GUIDES) {
    const rel = `skills/${guide.name}/SKILL.md`;
    const expected = await buildSkill(guide);
    let actual = null;
    try {
      actual = await readFile(join(projectRoot, rel), 'utf8');
    } catch {
      actual = null;
    }
    files.push({ rel, expected, actual, inSync: actual === expected });
  }
  return files;
}

async function checkSkills() {
  const state = await computeState();
  const drifted = state.filter((file) => !file.inSync);
  if (drifted.length > 0) {
    console.error(`[skills] out of sync (${drifted.length}):`);
    for (const file of drifted) {
      const reason = file.actual === null ? 'missing' : 'differs from docs/en/guide source';
      console.error(`  - ${file.rel}: ${reason}`);
    }
    console.error(`[skills] regenerate with 'corepack pnpm skills:generate'.`);
    return false;
  }
  console.log(`[skills] OK: ${state.length} guides match docs/en/guide/*.md`);
  return true;
}

async function writeSkills() {
  const state = await computeState();
  let changed = 0;
  for (const file of state) {
    if (file.actual === file.expected) continue;
    await writeFile(join(projectRoot, file.rel), file.expected, 'utf8');
    changed += 1;
  }
  console.log(`[skills] wrote ${changed} guide(s), ${state.length - changed} unchanged`);
}

async function main() {
  const mode = process.argv.includes('--check') ? 'check' : 'write';
  if (mode === 'check') {
    process.exit((await checkSkills()) ? 0 : 1);
  }
  await writeSkills();
}

const isCliEntry = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isCliEntry) {
  main().catch((error) => {
    console.error(
      `[skills] Fatal error: ${error instanceof Error ? error.message : String(error)}`,
    );
    process.exit(1);
  });
}
