// ── Types ──────────────────────────────────────────────────────────────────────

export interface EbpfAttachResult {
  success: boolean;
  error?: string;
  mode: 'live' | 'script' | 'simulated';
  pid: number;
  durationSec: number;
  syscallsTraced: string[];
  events?: SyscallEvent[];
  eventCount: number;
  /** When mode=script, the bpftrace script to execute. */
  script?: string;
  /** Usage instructions (for script mode). */
  usage?: string;
  /** Whether the platform can do live bpftrace attach. */
  liveCapable: boolean;
  /** Whether bpftrace binary was found. */
  bpftraceAvailable: boolean;
  /** Explicit watermark for simulated data. */
  isSimulated?: boolean;
  /**
   * Where the trace runs: the host kernel (device='host') or an Android
   * device kernel driven over adb (device='adb'). Stated explicitly so callers
   * never mistake a host trace for a device trace.
   */
  scope?: 'host-kernel' | 'device-kernel';
  /** Which executor produced (or would produce) the events. */
  backend?: 'host-bpftrace' | 'adb-bpftrace';
  /** Android serial that was traced when device='adb'. */
  device?: string;
  /** Which probe family the generated program uses (kprobe = BTF-free fallback). */
  probeStyle?: 'tracepoint' | 'kprobe';
  /** Node platform of the host that would execute bpftrace. */
  platform?: NodeJS.Platform;
  /** Actionable note when live capture is impossible or constrained. */
  note?: string;
  /** One-line remediation mirroring `note`. */
  fix?: string;
}

