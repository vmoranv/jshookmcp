function isValidSyscallName(name: string): boolean {
  const NAME_RE = /^[a-z][a-z0-9_]*$/;
  return NAME_RE.test(name) && name.length <= 64;
}

function isArgBool(args: Record<string, unknown>, key: string): boolean {
  return args[key] === true;
}

/**
 * Build a bpftrace script for the given pid + syscall filter + duration.
 * Mirrors the script generation in SyscallHookHandlers.handleSyscallEbpfTrace
 * but outputs raw JSONL (one JSON object per line) to stdout for machine
 * consumption.
 */
function buildTracepointScript(pid: number, syscalls: string[], durationSec: number): string {
  const pidFilter = pid > 0 ? `/pid == ${pid}/` : '';
  const tracepoints = syscalls.map((sc) => `tracepoint:syscalls:sys_enter_${sc}`).join(', ');
  const exitTracepoints = syscalls.map((sc) => `tracepoint:syscalls:sys_exit_${sc}`).join(', ');

  return `#!/usr/bin/env bpftrace
// Generated by jshookmcp syscall_ebpf_attach
// Target PID: ${pid || 'all'} | Duration: ${durationSec}s | Syscalls: ${syscalls.join(', ')}

BEGIN {
  printf("{\\"type\\":\\"start\\",\\"targetPid\\":%d,\\"durationSec\\":%d,\\"syscalls\\":[%s]}\\n",
    ${pid || 0}, ${durationSec}, "${syscalls.join('","')}");
}

${tracepoints} ${pidFilter}
{
  @enter_ts[tid] = nsecs;
  printf("{\\"type\\":\\"enter\\",\\"elapsedMs\\":%llu,\\"pid\\":%d,\\"tid\\":%d,\\"syscall\\":\\"%s\\",\\"args\\":\\"\\"",
    elapsed / 1000000, pid, tid, probe);
  if (probe == "tracepoint:syscalls:sys_enter_openat" || probe == "tracepoint:syscalls:sys_enter_open") {
    printf("\\"pathname\\": \\"%s\\", \\"flags\\": %d, \\"mode\\": %d", str(args->pathname), args->flags, args->mode);
  } else if (probe == "tracepoint:syscalls:sys_enter_read" || probe == "tracepoint:syscalls:sys_enter_write") {
    printf("\\"fd\\": %d, \\"count\\": %d", args->fd, args->count);
  } else if (probe == "tracepoint:syscalls:sys_enter_connect") {
    printf("\\"fd\\": %d", args->fd);
  } else if (probe == "tracepoint:syscalls:sys_enter_mmap") {
    printf("\\"addr\\": %llu, \\"length\\": %llu, \\"prot\\": %d, \\"flags\\": %d, \\"fd\\": %d",
      args->addr, args->length, args->prot, args->flags, args->fd);
  } else if (probe == "tracepoint:syscalls:sys_enter_execve") {
    printf("\\"filename\\": \\"%s\\"", str(args->filename));
  }
  printf("\\"}\\n");
}

${exitTracepoints} ${pidFilter}
{
  $elapsed_ns = nsecs - @enter_ts[tid];
  printf("{\\"type\\":\\"exit\\",\\"elapsedMs\\":%llu,\\"pid\\":%d,\\"tid\\":%d,\\"syscall\\":\\"%s\\",\\"ret\\":%d,\\"durationUs\\":%llu}\\n",
    elapsed / 1000000, pid, tid, probe, args->ret, $elapsed_ns / 1000);
  delete(@enter_ts[tid]);
}

interval:s:${durationSec} {
  printf("{\\"type\\":\\"stop\\",\\"elapsedMs\\":%llu}\\n", elapsed / 1000000);
  exit();
}

END {
  printf("{\\"type\\":\\"end\\",\\"elapsedMs\\":%llu}\\n", elapsed / 1000000);
  clear(@enter_ts);
}
`;
}

type BpftraceProbeStyle = 'tracepoint' | 'kprobe';

/**
 * BTF-free kprobe program. Kernels built without CONFIG_FTRACE_SYSCALLS expose
 * no syscalls:sys_enter_* tracepoints, and without kernel BTF bpftrace cannot
 * parse tracepoint arguments either. kprobes on the __arm64_sys_* wrappers need
 * neither: the syscall name is bound by the probe definition, so no argument
 * dereference (and therefore no BTF) is required.
 */
function buildKprobeScript(pid: number, syscalls: string[], durationSec: number): string {
  const pidFilter = pid > 0 ? ` /pid == ${pid}/` : '';
  const blocks: string[] = [];
  for (const sc of syscalls) {
    const symbol = `__arm64_sys_${sc}`;
    blocks.push(
      `kprobe:${symbol}${pidFilter}
{
  printf("{\\"type\\":\\"enter\\",\\"elapsedMs\\":%llu,\\"pid\\":%d,\\"tid\\":%d,\\"syscall\\":\\"${sc}\\",\\"args\\":\\"\\"}\\n",
    elapsed / 1000000, pid, tid);
}`,
      `kretprobe:${symbol}${pidFilter}
{
  printf("{\\"type\\":\\"exit\\",\\"elapsedMs\\":%llu,\\"pid\\":%d,\\"tid\\":%d,\\"syscall\\":\\"${sc}\\",\\"ret\\":%d}\\n",
    elapsed / 1000000, pid, tid, retval);
}`,
    );
  }

  return `#!/usr/bin/env bpftrace
// Generated by jshookmcp syscall_ebpf_attach (BTF-free kprobe mode)
// Target PID: ${pid === 0 ? 'all' : pid} | Duration: ${durationSec}s | Syscalls: ${syscalls.join(', ')}
// syscalls:sys_enter_* tracepoints are unavailable and/or kernel BTF is absent;
// count by kprobe on the __arm64_sys_* wrappers without argument dereference.

BEGIN { printf("{\\"type\\":\\"start\\",\\"targetPid\\":${pid === 0 ? 0 : pid},\\"durationSec\\":${durationSec}}\\n"); }

${blocks.join('\n\n')}

interval:s:${durationSec} { printf("{\\"type\\":\\"stop\\"}\\n"); exit(); }

END { printf("{\\"type\\":\\"end\\"}\\n"); }
`;
}

function buildBpftraceScript(
  pid: number,
  syscalls: string[],
  durationSec: number,
  style: BpftraceProbeStyle = 'tracepoint',
): string {
  return style === 'kprobe'
    ? buildKprobeScript(pid, syscalls, durationSec)
    : buildTracepointScript(pid, syscalls, durationSec);
}

/**
 * Parse bpftrace JSONL stdout lines into structured events.
 * Handles enter/exit pair correlation.
 */
function parseBpftraceJsonl(
  lines: string[],
  pid: number,
  syscalls: string[],
): {
  events: SyscallEvent[];
  warnings: string[];
  enterCount: number;
  exitCount: number;
} {
  const events: SyscallEvent[] = [];
  const warnings: string[] = [];
  let enterCount = 0;
  let exitCount = 0;
  // Map tid → last enter entry for pairing
  const pendingEntries = new Map<
    number,
    { elapsedMs: number; pid: number; syscall: string; args: string[] }
  >();

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed) continue;

    let parsed: Record<string, unknown>;
    try {
      parsed = JSON.parse(trimmed) as Record<string, unknown>;
    } catch {
      warnings.push(`Unparseable bpftrace line: ${trimmed.substring(0, 80)}`);
      continue;
    }

    const type = typeof parsed['type'] === 'string' ? parsed['type'] : undefined;
    if (type === 'start' || type === 'stop' || type === 'end') continue;

    if (type === 'enter') {
      enterCount++;
      handleBpftraceEnter(parsed, pid, syscalls, pendingEntries);
    } else if (type === 'exit') {
      exitCount++;
      handleBpftraceExit(parsed, pid, syscalls, pendingEntries, events);
    }
  }

  // Flush unmatched enter events as partial entries
  for (const [, enter] of pendingEntries) {
    events.push({
      timestamp: enter.elapsedMs,
      pid: enter.pid,
      syscall: enter.syscall,
      args: enter.args,
    });
  }

  return { events, warnings, enterCount, exitCount };
}

function extractSyscallName(probe: string, syscalls: string[]): string | undefined {
  // kprobe mode emits the bare syscall name (the probe binding carries it);
  // tracepoint mode emits "tracepoint:syscalls:sys_{enter,exit}_<name>".
  if (probe.length > 0 && syscalls.includes(probe)) return probe;
  const match = /sys_(?:enter|exit)_(\w+)$/.exec(probe);
  if (!match) return undefined;
  const name = match[1]!;
  return syscalls.includes(name) ? name : undefined;
}

function extractEnterArgs(parsed: Record<string, unknown>): string[] {
  const args: string[] = [];
  // Common args from the bpftrace script
  for (const key of [
    'pathname',
    'fd',
    'count',
    'flags',
    'mode',
    'addr',
    'length',
    'prot',
    'filename',
  ]) {
    const val = parsed[key];
    if (typeof val === 'string') args.push(`${key}=${val}`);
    else if (typeof val === 'number') args.push(`${key}=${val}`);
  }
  return args;
}

/**
 * Detect whether bpftrace is available on this system.
 */
async function probeBpftrace(): Promise<{
  available: boolean;
  liveCapable: boolean;
  reason?: string;
}> {
  // Only Linux can do live bpftrace
  if (process.platform !== 'linux') {
    return {
      available: false,
      liveCapable: false,
      reason: `Platform ${process.platform} does not support bpftrace`,
    };
  }

  try {
    const { execFile } = await import('node:child_process');
    const { promisify } = await import('node:util');
    const execFileAsync = promisify(execFile);
    const { stdout } = await execFileAsync('bpftrace', ['--version'], { timeout: 5000 });
    const version = stdout.trim();
    return {
      available: version.length > 0,
      liveCapable: true,
    };
  } catch {
    return {
      available: false,
      liveCapable: true, // Linux is capable, bpftrace just isn't installed
      reason:
        'bpftrace binary not found. Install with: apt install bpftrace (Debian/Ubuntu) or equivalent.',
    };
  }
}

/**
 * Spawn bpftrace live and parse its JSONL output.
 * Requires Linux with bpftrace + CAP_BPF or root.
 */
/** How to launch bpftrace: host binary directly, or adb exec on a device. */
interface BpftraceLaunch {
  command: string;
  args: string[];
  env?: NodeJS.ProcessEnv;
}

async function captureLiveBpftrace(
  pid: number,
  syscalls: string[],
  durationSec: number,
  launch?: BpftraceLaunch,
  style: BpftraceProbeStyle = 'tracepoint',
): Promise<{ events: SyscallEvent[]; warnings: string[]; script: string }> {
  const script = buildBpftraceScript(pid, syscalls, durationSec, style);
  const command = launch?.command ?? 'bpftrace';
  const args = launch?.args ?? ['-e', script];
  const env = launch?.env ?? { ...process.env };

  return new Promise((resolve, reject) => {
    // Dynamic import to avoid loading child_process where not needed
    import('node:child_process')
      .then(({ spawn }) => {
        const child = spawn(command, args, {
          stdio: ['ignore', 'pipe', 'pipe'],
          env,
        });

        const stdoutLines: string[] = [];
        let stdoutBuffer = '';
        const warnings: string[] = [];
        let stderr = '';
        let settled = false;

        // Flush any partial line left in the buffer (JSON lines split across
        // chunk boundaries must be reassembled before parsing).
        const flushStdout = () => {
          if (stdoutBuffer) {
            stdoutLines.push(stdoutBuffer);
            stdoutBuffer = '';
          }
        };

        const timer = setTimeout(
          () => {
            if (settled) return;
            settled = true;
            try {
              child.kill('SIGTERM');
            } catch {
              /* ignore */
            }
            // If we got some output, return what we have; otherwise timeout is an error
            flushStdout();
            if (stdoutLines.length > 0) {
              const { events, warnings: parseWarns } = parseBpftraceJsonl(
                stdoutLines,
                pid,
                syscalls,
              );
              resolve({ events, warnings: [...warnings, ...parseWarns], script });
            } else {
              reject(new Error(`bpftrace timed out after ${durationSec + 5}s with no output`));
            }
          },
          (durationSec + 5) * 1000,
        );

        child.stdout?.on('data', (chunk: Buffer) => {
          // Reassemble chunk-split JSON lines: keep the trailing partial line
          // in the buffer and only push complete lines for parsing.
          stdoutBuffer += chunk.toString();
          const lines = stdoutBuffer.split('\n');
          stdoutBuffer = lines.pop() ?? '';
          stdoutLines.push(...lines);
        });

        child.stderr?.on('data', (chunk: Buffer) => {
          stderr += chunk.toString();
          const lines = stderr.split('\n');
          // Keep the incomplete last entry
          const extra = lines.pop() ?? '';
          for (const line of lines) {
            if (line.trim()) warnings.push(line.trim());
          }
          stderr = extra;
        });

        child.on('error', (err: Error) => {
          if (settled) return;
          settled = true;
          clearTimeout(timer);
          reject(new Error(`bpftrace spawn failed: ${err.message}. Is bpftrace installed?`));
        });

        child.on('close', (code) => {
          if (settled) return;
          settled = true;
          clearTimeout(timer);
          // Flush remaining stderr
          if (stderr.trim()) warnings.push(stderr.trim());
          flushStdout();

          if (code !== 0 && stdoutLines.length === 0) {
            reject(new Error(`bpftrace exited with code ${code}: ${warnings.join('; ')}`));
            return;
          }

          const {
            events,
            warnings: parseWarns,
            enterCount,
            exitCount,
          } = parseBpftraceJsonl(stdoutLines, pid, syscalls);
          if (enterCount > 0 && exitCount === 0) {
            warnings.push(
              `No exit tracepoints captured. Ensure kernel supports sys_exit tracepoints.`,
            );
          }

          resolve({ events, warnings: [...warnings, ...parseWarns], script });
        });
      })
      .catch(reject);
  });
}

/**
 * Generate simulated events for testing/demo purposes.
 */
function generateSimulatedEvents(
  pid: number,
  syscalls: string[],
  durationSec: number,
): SyscallEvent[] {
  const events: SyscallEvent[] = [];
  const eventCount = Math.max(5, Math.min(syscalls.length * 3, Math.floor(durationSec * 4)));
  const stepMs = (durationSec * 1000) / eventCount;

  for (let i = 0; i < eventCount; i++) {
    const syscallIdx = i % syscalls.length;
    const syscall = syscalls[syscallIdx]!;
    const jitter = i > 0 ? (Math.random() - 0.5) * stepMs * 0.6 : 0;
    const timestamp = i * stepMs + jitter;

    events.push({
      timestamp: Math.max(0, Math.round(timestamp * 100) / 100),
      pid: pid || 1234,
      syscall,
      args: buildSimulatedArgs(syscall, i),
      returnValue: i % 4 === 0 ? -1 : (i + 1) * 64,
      duration: Math.round(Math.random() * 200) / 100,
    });
  }
  return events;
}

function buildSimulatedArgs(syscall: string, i: number): string[] {
  switch (syscall) {
    case 'read':
    case 'write':
      return [`fd=${(i % 7) + 3}`, `count=${(i + 1) * 128}`];
    case 'openat':
      return [
        `pathname=/tmp/jshook_${i}.log`,
        `flags=${i % 2 === 0 ? 'O_RDONLY' : 'O_RDWR'}`,
        `mode=0644`,
      ];
    case 'close':
      return [`fd=${(i % 7) + 3}`];
    case 'connect':
      return [`fd=${(i % 5) + 10}`, `addr=127.0.0.1:${8080 + i}`];
    case 'sendto':
    case 'recvfrom':
      return [`fd=${(i % 5) + 10}`, `count=${(i + 1) * 256}`];
    case 'mmap':
      return [`addr=0x0`, `length=${(i + 1) * 4096}`, `prot=${i % 2 === 0 ? 3 : 7}`, `flags=34`];
    case 'mprotect':
      return [`addr=0x7f000000`, `length=${(i + 1) * 4096}`, `prot=${i % 2 === 0 ? 1 : 7}`];
    case 'clone':
      return [`flags=0x3d0f00`];
    case 'execve':
      return [`filename=/usr/bin/sleep`];
    case 'ioctl':
      return [`fd=${(i % 7) + 3}`, `request=0x${(0x5400 + i).toString(16)}`];
    default:
      return [`arg0=0x${(100 + i).toString(16)}`];
  }
}

// ── Android (adb) backend ─────────────────────────────────────────────────────
// Reuses buildBpftraceScript + parseBpftraceJsonl verbatim: only the executor
// moves from a host child_process to `adb shell su -c` on the device. bpftrace
// and its prerequisites (kernel BTF for kprobe/tracepoint argument decoding)
// live on the phone, so there is no host/device protocol translation to keep
// in sync.

const ADB_SAFE_PATH = /^[A-Za-z0-9._/+-]+$/;

function resolveAdbBinary(): string {
  return readEnvString('ADB_PATH', 'adb', { trim: true });
}

function execAdbCommand(
  adbPath: string,
  args: string[],
  timeoutMs: number,
): Promise<{ stdout: string; stderr: string }> {
  return new Promise((resolve, reject) => {
    import('node:child_process')
      .then(({ execFile }) => {
        execFile(
          adbPath,
          args,
          { encoding: 'utf8', windowsHide: true, timeout: timeoutMs, maxBuffer: 8 * 1024 * 1024 },
          (error, stdout, stderr) => {
            if (error) {
              reject(new Error((stderr || error.message).trim()));
              return;
            }
            resolve({ stdout, stderr });
          },
        );
      })
      .catch(reject);
  });
}

async function probeDeviceBpftrace(
  serial: string,
  bpftracePath: string,
): Promise<{ available: boolean; reason?: string }> {
  const adbPath = resolveAdbBinary();
  // Trailing `|| true` keeps a plain "not found" from exiting non-zero —
  // otherwise execFile reports it as a failed command and the caller cannot
  // tell a missing binary from an adb/connection failure.
  const check = bpftracePath
    ? `test -x ${bpftracePath} && printf '%s' ${bpftracePath} || true`
    : 'command -v bpftrace || true';
  try {
    const { stdout } = await execAdbCommand(
      adbPath,
      ['-s', serial, 'shell', `su -c "${check}"`],
      15_000,
    );
    return stdout.trim().length > 0
      ? { available: true }
      : { available: false, reason: 'bpftrace was not found on the device (checked via su)' };
  } catch (error) {
    return { available: false, reason: error instanceof Error ? error.message : String(error) };
  }
}

/**
 * Pick the probe family for a device. Tracepoints need both the syscall
 * tracepoints (CONFIG_FTRACE_SYSCALLS) and kernel BTF to parse their arguments;
 * Android GKI images frequently ship neither. Anything short of both falls back
 * to BTF-free kprobes.
 */
async function probeDeviceTraceStyle(serial: string): Promise<BpftraceProbeStyle> {
  const adbPath = resolveAdbBinary();
  try {
    const { stdout } = await execAdbCommand(
      adbPath,
      [
        '-s',
        serial,
        'shell',
        'su -c "test -f /sys/kernel/btf/vmlinux && echo btf; test -d /sys/kernel/tracing/events/syscalls && echo tps"',
      ],
      15_000,
    );
    return stdout.includes('btf') && stdout.includes('tps') ? 'tracepoint' : 'kprobe';
  } catch {
    return 'kprobe';
  }
}

async function captureDeviceBpftrace(
  serial: string,
  bpftracePath: string,
  pid: number,
  syscalls: string[],
  durationSec: number,
  style: BpftraceProbeStyle = 'kprobe',
): Promise<{ events: SyscallEvent[]; warnings: string[]; script: string }> {
  const { writeFile, unlink } = await import('node:fs/promises');
  const { tmpdir } = await import('node:os');
  const { join } = await import('node:path');
  const { randomUUID } = await import('node:crypto');
  const adbPath = resolveAdbBinary();
  const script = buildBpftraceScript(pid, syscalls, durationSec, style);
  const id = randomUUID();
  const remotePath = `/data/local/tmp/jshook_ebpf_${id}.bt`;
  const localPath = join(tmpdir(), `jshook_ebpf_${id}.bt`);
  const binary = bpftracePath || 'bpftrace';
  await writeFile(localPath, script, 'utf8');
  try {
    await execAdbCommand(adbPath, ['-s', serial, 'push', localPath, remotePath], 30_000);
    return await captureLiveBpftrace(
      pid,
      syscalls,
      durationSec,
      {
        command: adbPath,
        args: ['-s', serial, 'shell', `su -c "${binary} ${remotePath}"`],
      },
      style,
    );
  } finally {
    await unlink(localPath).catch(() => {});
    await execAdbCommand(
      adbPath,
      ['-s', serial, 'shell', `su -c "rm -f ${remotePath}"`],
      15_000,
    ).catch(() => {});
  }
}
// ── Main Handler ───────────────────────────────────────────────────────────────

async function runAndroidEbpfAttach(
  args: Record<string, unknown>,
  effectivePid: number,
  durationSec: number,
  effectiveSyscalls: string[],
): Promise<EbpfAttachResult> {
  const base = {
    mode: 'script' as const,
    pid: effectivePid,
    durationSec,
    syscallsTraced: effectiveSyscalls,
    eventCount: 0,
    liveCapable: true,
    scope: 'device-kernel' as const,
    backend: 'adb-bpftrace' as const,
    platform: process.platform,
  };
  const serial = argString(args, 'serial');
  if (!serial) {
    return {
      ...base,
      success: false,
      bpftraceAvailable: false,
      error: "device='adb' requires `serial` (see adb_device_list)",
    };
  }
  try {
    assertValidDeviceSerial(serial);
  } catch (error) {
    return {
      ...base,
      success: false,
      bpftraceAvailable: false,
      device: serial,
      error: error instanceof Error ? error.message : String(error),
    };
  }
  const bpftracePath = argString(args, 'bpftracePath') ?? '';
  if (bpftracePath.length > 0 && !ADB_SAFE_PATH.test(bpftracePath)) {
    return {
      ...base,
      success: false,
      bpftraceAvailable: false,
      device: serial,
      error: 'bpftracePath must be a plain absolute path (no spaces or shell metacharacters)',
    };
  }

  const deviceProbe = await probeDeviceBpftrace(serial, bpftracePath);
  const traceStyle = await probeDeviceTraceStyle(serial);
  if (deviceProbe.available) {
    try {
      const { events, warnings: captureWarnings } = await captureDeviceBpftrace(
        serial,
        bpftracePath,
        effectivePid,
        effectiveSyscalls,
        durationSec,
        traceStyle,
      );
      return {
        success: true,
        mode: 'live',
        pid: effectivePid,
        durationSec,
        syscallsTraced: effectiveSyscalls,
        events,
        eventCount: events.length,
        liveCapable: true,
        bpftraceAvailable: true,
        scope: 'device-kernel',
        backend: 'adb-bpftrace',
        device: serial,
        probeStyle: traceStyle,
        platform: process.platform,
        ...(captureWarnings.length > 0 ? { note: captureWarnings.join('; ') } : {}),
      };
    } catch (error) {
      return {
        ...base,
        success: false,
        bpftraceAvailable: true,
        device: serial,
        error: `Android eBPF attach failed: ${error instanceof Error ? error.message : String(error)}`,
      };
    }
  }

  const deviceScript = buildBpftraceScript(
    effectivePid,
    effectiveSyscalls,
    durationSec,
    traceStyle,
  );
  return {
    ...base,
    success: true,
    bpftraceAvailable: false,
    device: serial,
    probeStyle: traceStyle,
    script: deviceScript,
    usage: `adb -s ${serial} push <script> /data/local/tmp/jshook.bt && adb -s ${serial} shell su -c 'bpftrace /data/local/tmp/jshook.bt'`,
    note: `bpftrace is not installed on device ${serial}${deviceProbe.reason ? ` (${deviceProbe.reason})` : ''}; the generated program targets the device kernel.`,
    fix: 'Push a static bpftrace build for the device ABI and add it to PATH or pass bpftracePath. Kprobe/tracepoint argument decoding also needs kernel BTF (/sys/kernel/btf/vmlinux); without BTF use tracepoint-only programs or tracefs kprobes.',
  };
}

export async function handleSyscallEbpfAttach(
  args: Record<string, unknown>,
): Promise<EbpfAttachResult> {
  // Parse pid — fail-closed: if pid key exists but is not a valid number, reject
  let pid: number | undefined;
  if (args['pid'] !== undefined && args['pid'] !== null) {
    pid = argNumber(args, 'pid');
    if (pid === undefined || !Number.isInteger(pid) || pid < 0) {
      return {
        success: false,
        error: 'pid must be a non-negative integer (0 for all processes)',
        pid: 0,
        durationSec: 0,
        syscallsTraced: [],
        eventCount: 0,
        mode: 'script',
        liveCapable: false,
        bpftraceAvailable: false,
      };
    }
  }
  const effectivePid = pid ?? 0;

  // Parse syscalls
  const rawSyscalls = argStringArray(args, 'syscalls');
  // If syscalls key was explicitly provided but we got nothing → invalid input
  if (args['syscalls'] !== undefined && rawSyscalls.length === 0) {
    return {
      success: false,
      error: 'syscalls must be an array of valid syscall name strings',
      pid: effectivePid,
      durationSec: 0,
      syscallsTraced: [],
      eventCount: 0,
      mode: 'script',
      liveCapable: false,
      bpftraceAvailable: false,
    };
  }
  const effectiveSyscalls =
    rawSyscalls.length > 0
      ? [...new Set(rawSyscalls.map((s) => s.trim().toLowerCase()).filter(Boolean))]
      : [...DEFAULT_SYSCALLS];

  // Validate syscall names
  const invalid = effectiveSyscalls.filter((s) => !isValidSyscallName(s));
  if (invalid.length > 0) {
    return {
      success: false,
      error: `Invalid syscall names (must be lowercase alphanumeric with underscores): ${invalid.join(', ')}`,
      pid: effectivePid,
      durationSec: 0,
      syscallsTraced: effectiveSyscalls,
      eventCount: 0,
      mode: 'script',
      liveCapable: false,
      bpftraceAvailable: false,
    };
  }

  // Parse durationSec — must be an integer: bpftrace `interval:s:<n>` rejects
  // non-integer values, so a float would produce an unparseable script.
  let durationSec = argNumber(args, 'durationSec') ?? SYSCALL_TRACE_DURATION_DEFAULT_SEC;
  if (!Number.isFinite(durationSec)) durationSec = SYSCALL_TRACE_DURATION_DEFAULT_SEC;
  if (
    !Number.isInteger(durationSec) ||
    durationSec < SYSCALL_TRACE_DURATION_MIN_SEC ||
    durationSec > SYSCALL_TRACE_DURATION_MAX_SEC
  ) {
    return {
      success: false,
      error: `durationSec must be an integer between ${SYSCALL_TRACE_DURATION_MIN_SEC} and ${SYSCALL_TRACE_DURATION_MAX_SEC}`,
      pid: effectivePid,
      durationSec,
      syscallsTraced: effectiveSyscalls,
      eventCount: 0,
      mode: 'script',
      liveCapable: false,
      bpftraceAvailable: false,
    };
  }

  // Simulate mode
  const simulate = isArgBool(args, 'simulate');
  if (simulate) {
    const events = generateSimulatedEvents(effectivePid, effectiveSyscalls, durationSec);
    return {
      success: true,
      mode: 'simulated',
      pid: effectivePid,
      durationSec,
      syscallsTraced: effectiveSyscalls,
      events,
      eventCount: events.length,
      liveCapable: process.platform === 'linux',
      bpftraceAvailable: false,
      isSimulated: true,
      scope: 'host-kernel',
      platform: process.platform,
    };
  }

  const deviceMode = argEnum(args, 'device', new Set(['host', 'adb'] as const), 'host');
  if (deviceMode === 'adb') {
    return runAndroidEbpfAttach(args, effectivePid, durationSec, effectiveSyscalls);
  }
  // Probe bpftrace availability
  const probe = await probeBpftrace();

  if (probe.available && probe.liveCapable) {
    // Attempt live capture
    try {
      const { events, warnings: captureWarnings } = await captureLiveBpftrace(
        effectivePid,
        effectiveSyscalls,
        durationSec,
      );
      return {
        success: true,
        mode: 'live',
        pid: effectivePid,
        durationSec,
        syscallsTraced: effectiveSyscalls,
        events,
        eventCount: events.length,
        liveCapable: true,
        bpftraceAvailable: true,
        scope: 'host-kernel',
        platform: process.platform,
        // Include warnings from capture in the script field as a note
        ...(captureWarnings.length > 0
          ? { script: `# Capture warnings:\n# ${captureWarnings.join('\n# ')}` }
          : {}),
      };
    } catch (err) {
      // Live capture failed — fall through to script fallback
      return {
        success: false,
        error: `Live eBPF attach failed: ${err instanceof Error ? err.message : String(err)}`,
        mode: 'script',
        pid: effectivePid,
        durationSec,
        syscallsTraced: effectiveSyscalls,
        eventCount: 0,
        liveCapable: true,
        bpftraceAvailable: probe.available,
      };
    }
  }

  // Script fallback — return the generated script for manual execution. The
  // generated program targets whatever kernel bpftrace later runs on; this
  // process can only reach the host, never a USB/adb device, so say so.
  const script = buildBpftraceScript(effectivePid, effectiveSyscalls, durationSec);
  const scopeNote = probe.liveCapable
    ? 'bpftrace is not installed on this Linux host; the generated program targets the host kernel.'
    : `bpftrace traces the ${process.platform} host kernel only — it cannot attach to an Android/Linux device over adb.`;
  const scopeFix = probe.liveCapable
    ? 'Install bpftrace (Debian/Ubuntu: `apt install bpftrace`) to enable live capture on the host.'
    : 'For an Android device: run a static bpftrace on-device (requires kernel BTF), or use adb with simpleperf / tracefs kprobes instead. For a Linux host: install bpftrace.';
  return {
    success: true,
    mode: 'script',
    pid: effectivePid,
    durationSec,
    syscallsTraced: effectiveSyscalls,
    eventCount: 0,
    script,
    usage: `bpftrace -e '${script.replace(/'/g, "'\\''")}'`,
    liveCapable: probe.liveCapable,
    bpftraceAvailable: probe.available,
    scope: 'host-kernel',
    platform: process.platform,
    note: scopeNote,
    fix: scopeFix,
  };
}

function handleBpftraceEnter(
  parsed: Record<string, unknown>,
  fallbackPid: number,
  syscalls: string[],
  pendingEntries: Map<number, { elapsedMs: number; pid: number; syscall: string; args: string[] }>,
): void {
  const tid = typeof parsed['tid'] === 'number' ? parsed['tid'] : undefined;
  const elapsedMs = typeof parsed['elapsedMs'] === 'number' ? parsed['elapsedMs'] : undefined;
  const eventPid = typeof parsed['pid'] === 'number' ? parsed['pid'] : fallbackPid;
  const syscall = extractSyscallName(
    typeof parsed['syscall'] === 'string' ? parsed['syscall'] : '',
    syscalls,
  );
  if (!syscall || tid === undefined || elapsedMs === undefined) return;

  const args = extractEnterArgs(parsed);
  pendingEntries.set(tid, { elapsedMs, pid: eventPid, syscall, args });
}

function handleBpftraceExit(
  parsed: Record<string, unknown>,
  fallbackPid: number,
  syscalls: string[],
  pendingEntries: Map<number, { elapsedMs: number; pid: number; syscall: string; args: string[] }>,
  events: SyscallEvent[],
): void {
  const tid = typeof parsed['tid'] === 'number' ? parsed['tid'] : undefined;
  const elapsedMs = typeof parsed['elapsedMs'] === 'number' ? parsed['elapsedMs'] : undefined;
  const ret = typeof parsed['ret'] === 'number' ? parsed['ret'] : undefined;
  const durationUs = typeof parsed['durationUs'] === 'number' ? parsed['durationUs'] : undefined;
  const syscallName = extractSyscallName(
    typeof parsed['syscall'] === 'string' ? parsed['syscall'] : '',
    syscalls,
  );

  if (tid === undefined || elapsedMs === undefined) return;

  const enter = pendingEntries.get(tid);
  const syscall = enter?.syscall ?? syscallName ?? 'unknown';
  const args = enter?.args ?? [];
  const pidForEvent =
    enter?.pid ?? (typeof parsed['pid'] === 'number' ? parsed['pid'] : fallbackPid);

  pendingEntries.delete(tid);

  events.push({
    timestamp: elapsedMs,
    pid: pidForEvent,
    syscall,
    args,
    returnValue: ret,
    duration: durationUs !== undefined ? durationUs / 1000 : undefined, // μs → ms
  });
}
